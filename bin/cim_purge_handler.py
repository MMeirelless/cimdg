"""
CIM Data Generator  -  REST handler for purging generated data.

Endpoint:
    POST /services/cimdg/purge  -  Delete all events from synthetic_cim index
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from splunk.persistconn.application import PersistentServerConnectionApplication
import splunk.rest as rest


class PurgeHandler(PersistentServerConnectionApplication):
    """Handle purge requests  -  delete all generated data."""

    def __init__(self, command_line, command_arg):
        PersistentServerConnectionApplication.__init__(self)

    def handle(self, in_string):
        try:
            args = json.loads(in_string)
            method = args.get("method", "GET")

            if method != "POST":
                return {
                    "status": 405,
                    "payload": json.dumps({"error": "Method not allowed. Use POST."}),
                }

            return self._handle_post(args)
        except Exception as e:
            return {
                "status": 500,
                "payload": json.dumps({"error": str(e)}),
            }

    def _handle_post(self, args):
        """Purge all events from the synthetic_cim index."""
        payload = args.get("payload", "{}")
        if isinstance(payload, bytes):
            payload = payload.decode("utf-8")
        data = json.loads(payload)

        if not data.get("confirm"):
            return {
                "status": 400,
                "payload": json.dumps({
                    "error": "Confirmation required. Send {\"confirm\": true} to proceed.",
                }),
            }

        index = data.get("index", "synthetic_cim")
        session_key = args["session"]["authtoken"]

        # Only delete events generated by this app (synthetic:* sourcetypes).
        # Never delete all data in the index  -  it could contain non-app data.
        search_query = (
            "search index=%s (sourcetype=cimdg:synthetic:*) | delete" % index
        )

        try:
            response, content = rest.simpleRequest(
                "/services/search/jobs",
                sessionKey=session_key,
                postargs={
                    "search": search_query,
                    "exec_mode": "normal",
                    "output_mode": "json",
                },
                method="POST",
            )

            if isinstance(content, bytes):
                content = content.decode("utf-8")

            job_info = json.loads(content)
            sid = job_info.get("sid", "")

            return {
                "status": 200,
                "payload": json.dumps({
                    "success": True,
                    "message": "Purge dispatched for synthetic:* events in index=%s "
                               "(job: %s). Only CIMDG-generated data will be removed."
                               % (index, sid),
                    "sid": sid,
                }),
            }
        except Exception as e:
            return {
                "status": 500,
                "payload": json.dumps({
                    "error": "Failed to dispatch purge: %s. "
                             "Ensure your user has the can_delete role."
                             % str(e),
                }),
            }
